-- ==============================================================================
-- R-TECH PURE WATER - SECURE DATABASE SCHEMA
-- ==============================================================================

-- 1. CUSTOMERS TABLE
create table if not exists public.customers (
    id bigint generated by default as identity primary key,
    name text not null check (char_length(trim(name)) between 2 and 100),
    email text not null check (email ~* '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$'),
    phone text not null check (char_length(trim(phone)) between 10 and 15),
    created_at timestamptz default now()
);

-- 2. WATER BOOKINGS TABLE
create table if not exists public.water_bookings (
    id bigint generated by default as identity primary key,
    name text not null check (char_length(trim(name)) between 2 and 100),
    email text not null check (email ~* '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$'),
    phone text not null check (char_length(trim(phone)) between 10 and 15),
    service text not null check (char_length(trim(service)) between 2 and 100),
    address text not null check (char_length(trim(address)) between 3 and 300),
    booking_date date not null,
    message text check (char_length(message) <= 1000),
    created_at timestamptz default now()
);

-- 3. CONTACTS TABLE
create table if not exists public.contacts (
    id bigint generated by default as identity primary key,
    name text not null check (char_length(trim(name)) between 2 and 100),
    email text not null check (email ~* '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$'),
    phone text check (phone is null or char_length(trim(phone)) between 10 and 15),
    subject text not null check (char_length(trim(subject)) between 2 and 150),
    message text not null check (char_length(trim(message)) between 3 and 2000),
    created_at timestamptz default now()
);

-- Indexes for performance
create index if not exists idx_water_bookings_date on public.water_bookings(booking_date);
create index if not exists idx_water_bookings_created on public.water_bookings(created_at desc);
create index if not exists idx_contacts_created on public.contacts(created_at desc);

-- ==============================================================================
-- ROW LEVEL SECURITY (RLS) POLICIES
-- ==============================================================================
alter table public.customers enable row level security;
alter table public.water_bookings enable row level security;
alter table public.contacts enable row level security;

-- Drop existing public / loose policies if recreating
drop policy if exists "public insert customers" on public.customers;
drop policy if exists "admins read customers" on public.customers;
drop policy if exists "public insert bookings" on public.water_bookings;
drop policy if exists "admins read bookings" on public.water_bookings;
drop policy if exists "public insert contacts" on public.contacts;
drop policy if exists "admins read contacts" on public.contacts;

-- Public Insert Policies (Anyone can submit a booking or contact message)
create policy "public insert customers"
    on public.customers
    for insert
    to anon, authenticated
    with check (true);

create policy "public insert bookings"
    on public.water_bookings
    for insert
    to anon, authenticated
    with check (true);

create policy "public insert contacts"
    on public.contacts
    for insert
    to anon, authenticated
    with check (true);

